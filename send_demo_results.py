def format_telegram_message(results):
    """Format sample results for Telegram"""
    ist = pytz.timezone('Asia/Kolkata')
    timestamp = datetime.now(ist).strftime('%Y-%m-%d %H:%M IST')

    message = f"""🚀 NSE PCS Scanner Results
{timestamp}

📊 Found {len(results)} stocks with bullish patterns

"""

    for i, stock in enumerate(results, 1):
        message += f"""{i}. {stock['symbol']}
   Price: ₹{stock['price']} | RSI: {stock['rsi']}
   Pattern: {stock['pattern']} ({int(stock['strength'])}/100)

"""

    message += """💡 Use for PCS trading strike selection analysis
✓ Generated by NSE PCS Scanner Automation
"""

    return message

def send_to_telegram(message):
    """Send message to Telegram"""
    token = os.getenv('TELEGRAM_BOT_TOKEN')
    chat_id = os.getenv('TELEGRAM_CHAT_ID')

    if not token or not chat_id:
        print("⚠ Telegram credentials not configured")
        print(f"\nTo send to Telegram, set these environment variables:")
        print(f"  export TELEGRAM_BOT_TOKEN='your_bot_token'")
        print(f"  export TELEGRAM_CHAT_ID='your_chat_id'")
        print(f"\nThen run: python send_demo_results.py")
        return False

    try:
        print(f"Sending to Telegram (Chat ID: {chat_id[:5]}...)...")
        url = f"https://api.telegram.org/bot{token}/sendMessage"
        data = {
            'chat_id': chat_id,
            'text': message,
            'parse_mode': 'HTML'
        }

        response = requests.post(url, json=data, timeout=10)
        if response.status_code == 200:
            print("✓ Message sent to Telegram successfully!")
            return True
        else:
            print(f"✗ Failed: HTTP {response.status_code}")
            return False
    except Exception as e:
        print(f"✗ Error: {str(e)}")
        return False

