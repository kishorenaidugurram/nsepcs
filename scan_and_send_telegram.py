"""
NSE F&O PCS Scanner - Telegram Reporter
Sends stock analysis results to Telegram
"""
import os
import sys
import json
import urllib.request
import urllib.parse
from datetime import datetime

# Get Telegram credentials from environment
TELEGRAM_BOT_TOKEN = os.getenv('TELEGRAM_BOT_TOKEN')
TELEGRAM_CHAT_ID = os.getenv('TELEGRAM_CHAT_ID')

if not TELEGRAM_BOT_TOKEN or not TELEGRAM_CHAT_ID:
    print("❌ ERROR: Telegram credentials not configured")
    print("\nTo use this script, set these environment variables:")
    print("  export TELEGRAM_BOT_TOKEN='your_bot_token_here'")
    print("  export TELEGRAM_CHAT_ID='your_chat_id_here'")
    print("\nExample usage:")
    print("  TELEGRAM_BOT_TOKEN='123:ABC' TELEGRAM_CHAT_ID='456' python3 scan_and_send_telegram.py")
    sys.exit(1)

def send_telegram_message(message):
    """Send message to Telegram using Bot API"""
    try:
        url = f"https://api.telegram.org/bot{TELEGRAM_BOT_TOKEN}/sendMessage"
        data = urllib.parse.urlencode({
            'chat_id': TELEGRAM_CHAT_ID,
            'text': message,
            'parse_mode': 'HTML'
        }).encode('utf-8')

        req = urllib.request.Request(url, data=data)
        with urllib.request.urlopen(req, timeout=10) as response:
            result = json.loads(response.read().decode('utf-8'))

            if result.get('ok'):
                print(f"✅ Message sent to Telegram successfully")
                return True
            else:
                print(f"❌ Telegram API error: {result.get('description', 'Unknown error')}")
                return False
    except Exception as e:
        print(f"❌ Failed to send Telegram message: {str(e)}")
        return False

