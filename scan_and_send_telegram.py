def format_results_for_telegram(results):
    """Format results as Telegram message"""
    current_time = datetime.now().strftime('%Y-%m-%d %H:%M IST')

    message = f"""<b>🚀 NSE F&O PCS Scanner - Bullish Momentum Stocks</b>
<i>{current_time}</i>

<b>📊 Found {len(results)} stocks meeting filter criteria:</b>

"""

    for i, stock in enumerate(results[:15], 1):  # Top 15
        symbol = stock['symbol']
        score = stock['score']
        metrics = stock['metrics']

        # Emoji based on score
        if score >= 75:
            emoji = "🟢"
            confidence = "HIGH"
        elif score >= 60:
            emoji = "🟡"
            confidence = "MEDIUM"
        else:
            emoji = "🟠"
            confidence = "LOW"

        message += f"{emoji} <b>{symbol}</b> [{confidence}]\n"
        message += f"   Score: {score} | RSI: {metrics['rsi']} | Price: ₹{metrics['price']}\n"

    if len(results) > 15:
        message += f"\n... and {len(results) - 15} more stocks\n"

    high_conf = len([r for r in results if r['score'] >= 75])
    med_conf = len([r for r in results if 60 <= r['score'] < 75])

    message += f"""
<b>📈 Summary:</b>
• <b>Total Stocks:</b> {len(results)}
• <b>🟢 HIGH Confidence (75+):</b> {high_conf}
• <b>🟡 MEDIUM Confidence (60-74):</b> {med_conf}

<b>ℹ️ Next Steps:</b>
1. Review stocks on NSE F&O PCS Scanner
2. Check technical charts for confirmation
3. Monitor RSI for entry signals
4. Set proper stop losses before trading

<i>Generated by NSE F&O PCS Scanner</i>"""

    return message

